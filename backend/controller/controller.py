def safe_filename(name: str) -> str:
    # sanitize a string for use as filename
    s = str(name or "")
    s = re.sub(r"[^\w\-.]", "_", s) #find each character which is not letter, number, _ , - or . and change them into _
    return s

def ensure_inventory_dir():
    # ensure existence of inventory directory
    os.makedirs(INVENTORY_DIR, exist_ok=True)
    return INVENTORY_DIR

def get_playbook_template_path(kind: str, is_virtual: bool = False):
    """
    Return the path of playbook template for 'grant' or 'revoke' in the folder INVENTORY_DIR, None otherwise.
      - grant  -> <CONTROLLER_PLAYBOOKS_DIR>/grant_playbook.yml
      - revoke -> <CONTROLLER_PLAYBOOKS_DIR>/revoke_playbook.yml
    """
    kind = (kind or "").lower()
    # check playbook type
    if kind == "grant":
        filename = "grant_containerlab_playbook.yml" if is_virtual else "grant_playbook.yml"
    elif kind == "revoke":
        filename = "revoke_containerlab_playbook.yml" if is_virtual else"revoke_playbook.yml"
    else:
        return None

    path = os.path.join(CONTROLLER_PLAYBOOKS_DIR, filename)
    return path if os.path.exists(path) else None

def write_inventory(reservation_id: int, devices: list):
    """
    Create INI inventory file with hosts that have ip_device not None.
    devices: list of dict {"id_device", "ip_device", "role"}
    Returns path to inventory file and list of hostnames written.
    """
    inv_dir = ensure_inventory_dir()
    safe_res = safe_filename(f"res-{reservation_id}-inventory")
    inv_path = os.path.join(inv_dir, f"{safe_res}.ini")

    hosts_written = []
    #write inventory
    with open(inv_path, "w", encoding="utf-8") as fh:
        fh.write("# Inventory generated by controller\n")
        fh.write("[all]\n")
        for d in devices:
            asset = d.get("id_device")
            role = (d.get("role") or "").lower()
            ip = d.get("ip_device")
            interface = d.get("interface")
            if not ip:
                print("Skipping device without IP:", asset)
                continue
            # if asset tag missing, take the ip and change . with _ to create a valid string
            host_key = safe_filename(asset) if asset else ip.replace(".", "_")

            # pick credentials depending on role
            if role == "host":
                ansible_user = MINIPC_USER
                ansible_ssh_pass = MINIPC_PASS
            else:
                ansible_user = SONIC_USER
                ansible_ssh_pass = SONIC_PASS

            # compose inventory line. We include ansible_ssh_pass and ansible_become_pass
            line = (
                f"{host_key} "
                f"ansible_host={ip} "
                f"ansible_user={ansible_user} "
                f"ansible_ssh_pass={ansible_ssh_pass} "
                f"ansible_python_interpreter=/usr/bin/python3 "
                f"ansible_become=yes "
                f"ansible_become_pass={ansible_ssh_pass} "
                f"asset_tag={asset} role={role} "
                f"res_iface={interface}\n"
            )

            fh.write(line)
            hosts_written.append(host_key)

    return inv_path, hosts_written

# function to convert window path into wsl compatible
def win_to_wsl_path(path):
    return "/mnt/" + path.replace("\\", "/").replace(":", "").lower()

def run_ansible_playbook(inventory_path: str, playbook_path: str, extra_vars: dict = None, timeout: int = 900, remote_user: str = None):
    # function to run ansible-playbook
    if extra_vars is None:
        extra_vars = {}
    
    containerlab_test = extra_vars.get("containerlab_test")
    if containerlab_test is not None:
        is_virtual = bool(containerlab_test)
    else:
        # get reservation_id from extra_vars if present, and check in database for virtual reservation
        reservation_id = extra_vars.get("reservation_id")
        is_virtual = get_is_virtual_from_db(reservation_id) if reservation_id is not None else False
        
    if LOCAL_TEST:
        inv_path_wsl = win_to_wsl_path(inventory_path)  #convert paths if test mode, otherwise use normal path
        pb_path_wsl = win_to_wsl_path(playbook_path)

        cmd = ["wsl", "ansible-playbook", "-i", inv_path_wsl, pb_path_wsl]
    else:
        if is_virtual:
             # if virtual reservation, use proxy command to reach devices through containerlab host
            proxy_cmd = f"-o StrictHostKeyChecking=no -o ProxyCommand=\"ssh -W %h:%p -o StrictHostKeyChecking=no {CONTAINERLAB_HOST_USER}@{CONTAINERLAB_HOST}\""
            extra_vars['ansible_ssh_common_args'] = proxy_cmd
    
        cmd = ["ansible-playbook", "-i", inventory_path, playbook_path]

    cmd += ["--forks", "15"]                                # useful for parallel operations


    if remote_user:
        extra_vars['ansible_become'] = True
        extra_vars['ansible_become_user'] = remote_user         # execute playbook as remote user
        extra_vars['ansible_become_method'] = 'sudo'
        extra_vars['ansible_ssh_pipelining'] = True             # avoid interactive prompts
        extra_vars['ansible_become_timeout'] = 5                # wait only 5 seconds if user does not insert the password

        print(f"[ANSIBLE] Forcing remote_user={remote_user}", flush=True)

    if extra_vars:
        cmd += ["--extra-vars", json.dumps(extra_vars)]     # add extra vars if present
    print("Running:", " ".join(cmd))
    try:
        #proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout) #run playbook as subprocess
        #return proc.returncode, proc.stdout, proc.stderr
    #except subprocess.TimeoutExpired as te:
        #return 124, "", f"TimeoutExpired: {te}"
        proc = subprocess.Popen(
            cmd,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            bufsize=1,
            universal_newlines=True
        )

        stdout_lines = []
        stderr_lines = []

        # read real time result
        start_time = time.time()

        while True:
            if time.time() - start_time > timeout:
                proc.kill()
                return 124, ''.join(stdout_lines), f"TimeoutExpired after {timeout}s"

            # check if process is terminated
            if proc.poll() is not None:
                break

            # read stdout
            line = proc.stdout.readline()
            if line:
                print(line.rstrip())  # print in real time
                stdout_lines.append(line)

            time.sleep(0.1)  # small pause

        # read remaining lines
        remaining_out = proc.stdout.read()
        if remaining_out:
            print(remaining_out.rstrip())
            stdout_lines.append(remaining_out)

        remaining_err = proc.stderr.read()
        if remaining_err:
            stderr_lines.append(remaining_err)

        stdout = ''.join(stdout_lines)
        stderr = ''.join(stderr_lines)

        return proc.returncode, stdout, stderr

    except Exception as e:
        return 1, "", str(e)

def create_res_playbook_template(username, reservation_id, devices, is_virtual=False):
    # function to create template of playbooks that
    # add become properties to playbook

    template_source = INPUT_TEMPLATE_CONTENT


    if is_virtual:
        template_source = re.sub(
            r'(^(\s*)vars:\s*\n)(\s*commands_map:)',
            lambda lm: (
                lm.group(1)
                + lm.group(2) + "  ansible_ssh_pipelining: true\n"
                + lm.group(2) + "  ansible_ssh_common_args: '-o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null'\n"
                + lm.group(3)
            ),
            template_source,
            count=1,
            flags=re.MULTILINE
        )

    template_with_become = re.sub(
        r'(^\s*- name:\s*Run commands from commands_map\s*\n)(\s*)(vars:)',
        lambda val: (
                val.group(1)
                + val.group(2)
                + "become: yes\n"
                + val.group(2)
                + f"become_user: {username}\n"
                + val.group(2)
                + "become_method: sudo\n"
                + val.group(2)
                + "vars:"
        ),
        template_source,
        flags=re.MULTILINE
    )
    # ensure controllerPlaybooks dir exists (folder next to BASE_DIR)
    os.makedirs(CONTROLLER_PLAYBOOKS_DIR, exist_ok=True)

    # output filename: res_<reservation_id>_playbook_template.yml, this file will be inserted in controllerPlaybooks folder
    safe_out_name = safe_filename(f"res_{reservation_id}_playbook_template")
    out_filename = f"{safe_out_name}.yml"
    out_path = os.path.join(CONTROLLER_PLAYBOOKS_DIR, out_filename)

    # build the commented entries to insert into the template as examples for user
    entries = []

    for d in devices:
        host  = d.get("id_device")
        ip = "192.168.15.10"
        if d.get("role") != "host" or is_virtual:
            iface = "eth1"
        else:
            iface = "enp1s0"
        entries.append((host, ip, iface))
    indent = None
    # find line to insert commented lines for each device
    m = re.search(r'^(\s*)#\s*insert a list of commands after each device\s*$', template_with_become,
                  flags=re.MULTILINE)
    if m:
        indent = m.group(1)  # leading whitespace of the comment line

    else:
        # fallback: if placeholder not found, try to insert after 'commands_map:' line
        m = re.search(r'^(?P<indent>\s*)commands_map:\s*\n', template_with_become, flags=re.MULTILINE)
        if m:
            indent = m.group("indent") + "  "  # place entries under commands_map with extra indent

    entries_lines = []
    for (host, ip, iface) in entries:
        # same indent as comment 'insert a list of commands after each device' for first line
        entries_lines.append(f"{indent}#{host}:")
        # same indent + two spaces for the command comment
        entries_lines.append(f"{indent}  #- ip addr add {ip}/24 dev {iface}")
    generated_block = "\n".join(entries_lines) if entries_lines else f"{indent}# (no hosts found in inventory)"  # insert comment if no host is found

    # insert generated_block immediately after the placeholder comment line, but keep the placeholder comment in the file
    insert_pos = m.end()  # end of the matched comment line
    final_content = template_with_become[:insert_pos] + "\n" + generated_block + template_with_become[insert_pos:]

    # write file to controllerPlaybooks
    try:
        with open(out_path, "w", encoding="utf-8") as fh:
            fh.write(final_content)
    except Exception as e:
        return jsonify({"ok": False, "message": f"Failed to write file: {e}"}), 500

